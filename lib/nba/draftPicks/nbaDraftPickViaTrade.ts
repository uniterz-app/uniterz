export function getDraftPickViaTrade(pickId: string): DraftPickViaTrade | undefined {
  return NBA_DRAFT_PICK_VIA_TRADE[pickId];
}

export type DraftPickOriginDisplay = {
  /** モーダル見出し */
  labelJa: string;
  labelEn: string;
  /** 本文 */
  textJa: string;
  textEn: string;
  /** トレードで動いたピックか */
  isTradeRelated: boolean;
};

type DraftPickOriginInput = {
  id: string;
  kind?: string;
  isOutgoing?: boolean;
  isSwap?: boolean;
  viaTradeJa?: string;
  viaTradeEn?: string;
};

/**
 * モーダル用: 全ピックに「獲得 / 放出 / 自前」の経緯を返す。
 * 自前（トレードなし）も明示する。
 * pick 上の viaTrade が欠ける場合でも id でマップを引く。
 */
export function resolveDraftPickOrigin(pick: DraftPickOriginInput): DraftPickOriginDisplay {
  const fromMap = pick.id ? getDraftPickViaTrade(pick.id) : undefined;
  const viaJa = pick.viaTradeJa ?? fromMap?.viaTradeJa ?? pick.viaTradeEn ?? fromMap?.viaTradeEn;
  const viaEn = pick.viaTradeEn ?? fromMap?.viaTradeEn ?? pick.viaTradeJa ?? fromMap?.viaTradeJa;
  if (viaJa || viaEn) {
    const blob = `${viaJa ?? ""} ${viaEn ?? ""}`;
    const isOut =
      pick.isOutgoing === true ||
      pick.kind === "outgoing" ||
      pick.kind === "forfeited" ||
      /放出|Sent out|没収|Forfeit/i.test(blob);
    const isSwap =
      pick.isSwap === true ||
      (/で取得|スワップ|swap/i.test(blob) && pick.kind !== "forfeited");
    if (pick.kind === "forfeited" || /没収|Forfeit/i.test(blob)) {
      return {
        labelJa: "没収経緯",
        labelEn: "FORFEITED",
        textJa: viaJa ?? viaEn!,
        textEn: viaEn ?? viaJa!,
        isTradeRelated: false,
      };
    }
    if (isOut) {
      return {
        labelJa: "放出経緯",
        labelEn: "SENT OUT VIA",
        textJa: viaJa ?? viaEn!,
        textEn: viaEn ?? viaJa!,
        isTradeRelated: true,
      };
    }
    if (isSwap) {
      return {
        labelJa: "スワップ経緯",
        labelEn: "SWAP ORIGIN",
        textJa: viaJa ?? viaEn!,
        textEn: viaEn ?? viaJa!,
        isTradeRelated: true,
      };
    }
    return {
      labelJa: "獲得経緯",
      labelEn: "ACQUIRED VIA",
      textJa: viaJa ?? viaEn!,
      textEn: viaEn ?? viaJa!,
      isTradeRelated: true,
    };
  }
  return {
    labelJa: "保有経緯",
    labelEn: "ORIGIN",
    textJa: "自前の指名権（トレードでの獲得・放出なし）",
    textEn: "Own pick (not acquired or sent out via trade)",
    isTradeRelated: false,
  };
}
