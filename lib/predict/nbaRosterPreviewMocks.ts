function cloneReport(base: NbaRosterReport): NbaRosterReport {
  return structuredClone(base);
}

export function rosterForPreset(
  presetId: string,
  homeTeamId: string,
  awayTeamId: string,
  homeTeamName: string,
  awayTeamName: string
): NbaRosterReport {
  const base =
    NBA_ROSTER_BY_PRESET[presetId] ?? NBA_ROSTER_BY_PRESET["both-teams-rich"]!;
  const report = cloneReport(base);
  report.home.teamId = homeTeamId;
  report.home.teamName = homeTeamName;
  report.away.teamId = awayTeamId;
  report.away.teamName = awayTeamName;
  return report;
}

function matchupKey(homeTeamId: string, awayTeamId: string): string {
  return `${homeTeamId.trim()}|${awayTeamId.trim()}`;
}

function rp(
  id: number,
  firstName: string,
  lastName: string,
  position: string,
  jerseyNumber: string,
  starter: boolean,
  mpg: number,
  ppg: number,
  rpg: number,
  apg: number,
  extra?: Partial<NbaRosterPlayer>
): NbaRosterPlayer {
  return {
    id,
    firstName,
    lastName,
    position,
    jerseyNumber,
    starter,
    gp: starter ? 62 : 48,
    mpg,
    ppg,
    rpg,
    apg,
    fgPct: starter ? 0.48 : 0.44,
    fgm: +(ppg * 0.37).toFixed(1),
    fga: +(ppg * 0.8).toFixed(1),
    fg3Pct: starter ? 0.37 : 0.35,
    fg3m: +(ppg * 0.12).toFixed(1),
    fg3a: +(ppg * 0.33).toFixed(1),
    ftPct: 0.8,
    ftm: +(ppg * 0.16).toFixed(1),
    fta: +(ppg * 0.2).toFixed(1),
    spg: starter ? 1.1 : 0.6,
    bpg: position.includes("C") ? 1.6 : starter ? 0.5 : 0.3,
    tpg: starter ? 2.4 : 1.1,
    dimmed: extra?.dimmed ?? (!starter && mpg < 16),
    ...extra,
  };
}

