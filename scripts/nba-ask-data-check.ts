async function main() {
  const only = process.argv.includes("--only") ? process.argv[process.argv.indexOf("--only") + 1] : null;
  const db = getAdminDb();
  let ok = 0;
  let ng = 0;
  for (const c of CASES.filter((x) => !only || x.q.includes(only))) {
    const intent = emptyNbaAskIntent({ kind: "nba", ...c.intent });
    let line = "";
    let pass = false;
    try {
      const r = await answerNbaAskQuery({ db, language: "ja", timeZone: "Asia/Tokyo", uid: "data-check", question: c.q, isPro: true }, intent);
      const empty = /まだありません|見つかりませんでした|ありません。$|データはアプリにありません/.test(r.answer) && !r.board && !r.games && !r.moves;
      const v = !r.view
        ? ""
        : r.view.kind === "today"
          ? ["today", r.view.stat].join("/")
          : r.view.kind === "team" || r.view.kind === "player"
            ? [r.view.kind, r.view.section, r.view.tab, r.view.group].filter(Boolean).join("/")
            : [r.view.kind, r.view.id].join("/");
      const viewOk = c.view === undefined || (c.view === false ? !v : v.startsWith(c.view));
      pass = (!empty || c.emptyOk === true) && (!c.expect || c.expect.test(r.answer)) && viewOk;
      line = r.answer.split("\n")[0]!.slice(0, 120);
      if (r.board) line += `  [表 ${r.board.rows.length}行: ${r.board.rows.slice(0, 2).map((x) => `${x.label} ${x.cells.join("/")}`).join(" | ")}]`;
      if (r.games) line += `  [試合カード ${r.games.length}]`;
      if (r.view) line += `  [UI: ${v} ${r.view.id}${"count" in r.view && r.view.count ? ` x${r.view.count}` : ""}]`;
      if (r.moves) line += `  [IN/OUT: IN ${r.moves.moves.incoming.length} ${r.moves.moves.incoming.slice(0, 2).map((m) => `${m.firstName} ${m.lastName}`).join(" | ")} / OUT ${r.moves.moves.outgoing.length}]`;
    } catch (e) {
      line = `ERROR ${e instanceof Error ? e.message : String(e)}`;
    }
    if (pass) ok++;
    else ng++;
    console.log(`${pass ? "OK" : "NG"}  ${c.q}\n    ${line}`);
  }
  console.log(`\n${ok}/${ok + ng} OK（AI は使っていません・Firestore 読み取りのみ）`);
}

void main();
